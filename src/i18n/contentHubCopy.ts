export const contentHubText = (language: LanguageCode, source: string, ...values: unknown[]): string => {
  const copy = language === 'en' && Object.hasOwn(contentHubEnglish, source) ? contentHubEnglish[source] : source;
  return copy.replace(/\{(\d+)\}/g, (placeholder, index: string) =>
    Number(index) < values.length ? String(values[Number(index)]) : placeholder);
};
