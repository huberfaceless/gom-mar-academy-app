export function emailCampaignText(language: LanguageCode, source: string, ...values: (string | number)[]): string {
  const copy = language === 'en' && Object.hasOwn(english, source) ? english[source] : source;
  return copy.replace(/\{(\d+)\}/g, (_, index: string) => String(values[Number(index)] ?? ''));
}
