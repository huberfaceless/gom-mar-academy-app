/** Internal editorial links are not paid recommendations. Keep the existing external-link policy. */
export function blogLinkRel(href?: string): string {
  try {
    if (new URL(href || '').origin === 'https://vital50.gomo-marketing.at') return 'noopener noreferrer';
  } catch { /* Relative links are not generated by the WordPress connector. */ }
  return 'noopener noreferrer sponsored';
}
