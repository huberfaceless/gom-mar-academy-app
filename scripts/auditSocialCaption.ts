import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildSocialCaption, splitSocialCaption } from '../src/utils/socialCaption';
import { socialEditorialContent, updateSocialEditorialContent } from '../src/utils/socialEditorialReview';
import type { PinterestPin } from '../src/types/contentEngine';

const description = 'Mehr erfahren. #VitaminC #Gesundheit50plus #vitaminc';
const keywords = ['Vitamin C', '#VitaminC', 'Gesundheit50plus', 'Immunsystem stärken', 'IMMUNSYSTEMSTÄRKEN'];
const split = splitSocialCaption(description, keywords);
assert.equal(split.description, 'Mehr erfahren.');
assert.deepEqual(split.keywords, ['Vitamin C', 'Gesundheit50plus', 'Immunsystem stärken']);
assert.equal(buildSocialCaption(description, keywords), 'Mehr erfahren.\n\n#VitaminC #Gesundheit50plus #Immunsystemstärken');
assert.equal(buildSocialCaption(buildSocialCaption(description, keywords), keywords), buildSocialCaption(description, keywords), 'Formatting twice must not duplicate hashtags.');
assert.equal(splitSocialCaption('Quelle: https://example.com/post#abschnitt #Wissen', []).description, 'Quelle: https://example.com/post#abschnitt');
assert.equal(splitSocialCaption('## Überschrift\n\nText.', []).description, '## Überschrift\n\nText.');
assert.equal(buildSocialCaption('Schon #Älter50 informiert.', ['älter50', 'ÄLTER50']), 'Schon informiert.\n\n#älter50');
assert.equal(buildSocialCaption('Text. #Mu\u0308digkeit', ['Müdigkeit']), 'Text.\n\n#Müdigkeit');
assert.equal(buildSocialCaption('Nur Text', []), 'Nur Text');
assert.equal(buildSocialCaption('', []), '');
const pin = { id: 'one', title: 'Ein Titel', description, keywords, targetUrl: 'https://example.com/artikel/' } as PinterestPin;
const draft = socialEditorialContent(pin, 'pinterest');
assert.equal(draft.ctaButtonText, 'Jetzt lesen →', 'The editor must show the actual graphic default.');
assert.equal(draft.description, 'Mehr erfahren.');
assert.deepEqual(draft.keywords, split.keywords);
const saved = updateSocialEditorialContent([pin], 'one', 'instagram', { ...draft, description: 'Neu geprüft. #VitaminC #Wissen', keywords: ['Vitamin C'] });
assert.equal(saved[0].instagramContent?.description, 'Neu geprüft.');
assert.deepEqual(saved[0].instagramContent?.keywords, ['Vitamin C', 'Wissen']);
assert.equal(saved[0].description, description, 'Instagram corrections must preserve the Pinterest record.');
assert.equal(buildSocialCaption(saved[0].instagramContent?.description, saved[0].instagramContent?.keywords), 'Neu geprüft.\n\n#VitaminC #Wissen');
for (const path of ['src/components/ContentEngine/InstagramPublishModal.tsx', 'src/components/ContentEngine/InstagramPostsTab.tsx', 'src/components/ContentEngine/ContentCalendarTab.tsx']) assert.match(readFileSync(path, 'utf8'), /buildSocialCaption/);
const modal = readFileSync('src/components/ContentEngine/SocialEditorialReviewModal.tsx', 'utf8');
assert.match(modal, /<a href=\{targetLink\}[^>]*aria-label=\{hubText\('Grafikvorschau: Zielseite öffnen'\)\}/);
assert.match(modal, /Der CTA ist Text im Bild, keine eigene Schaltfläche/);
assert.match(readFileSync('server.ts', 'utf8'), /Pin-Beschreibung als Fließtext ohne Hashtags/);
console.log('Social-Captions: getrennte Felder, keine doppelten Hashtags, Groß-/Kleinschreibung, bestehende Beschreibungen, URL-Fragmente, CTA-Standard und verlinkte Academy-Vorschau geprüft.');
